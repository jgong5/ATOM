# Regenerate cpu_gate_durations.txt, the seconds by which gate_cpu.sh packs
# its pytest processes: run this tree's CPU gate with --durations=0 and sum,
# per test file, the setup, call and teardown pytest reports for its tests
# (pytest leaves out a phase under 5 ms). Run it as the gate runs, in the CPU
# container on a snapshot with no other gate beside it, so the seconds are
# read under the gate's own load, and again when a test file's time moves.
# Arguments go to gate_cpu.sh. The table is written only from a green pytest
# run that reported at least one duration.
set -uo pipefail
. "$(dirname -- "${BASH_SOURCE[0]}")/_lib.sh"

ROOT=$(compass_tree_root) || exit $?
OUT=$ROOT/scripts/compass/cpu_gate_durations.txt
LOG=$(mktemp) || exit 96
trap 'rm -f "$LOG" "$OUT.tmp"' EXIT
env -u COMPASS_GATE_SELECT "$ROOT/scripts/compass/gate_cpu.sh" --durations=0 "$@" | tee "$LOG"
grep -qx 'pytest: rc=0' "$LOG" || { echo "regen: pytest was not green; $OUT left untouched" >&2; exit 1; }
{
    printf '# Seconds per test file in the CPU gate, by which gate_cpu.sh packs its\n'
    printf '# processes. Generated by regen_cpu_gate_durations.sh; never hand-edit.\n'
    awk '$1 ~ /^[0-9.]+s$/ && $2 ~ /^(setup|call|teardown)$/ && $3 ~ /::/ { split($3, a, "::"); t[a[1]] += $1 }
        END { for (f in t) printf "%.1f %s\n", t[f], f }' "$LOG" | sort -k2,2
} >"$OUT.tmp"
grep -q '^[0-9]' "$OUT.tmp" || { echo "regen: pytest reported no durations; $OUT left untouched" >&2; exit 96; }
mv -f "$OUT.tmp" "$OUT"
printf 'wrote %s: %s test files\n' "$OUT" "$(grep -c '^[0-9]' "$OUT")"
